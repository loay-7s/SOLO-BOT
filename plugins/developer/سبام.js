// plugins/سبام.js

const MAX_SPAM = 200;
const SPAM_DELAY = 300;

// ============================================================
// ⏱️ تأخير بين الرسائل
// ============================================================

const sleep = ms =>
    new Promise(resolve => setTimeout(resolve, ms));

// ============================================================
// 📱 التحقق من رقم الهاتف
// ============================================================

const isPhoneNumber =
    value =>
        /^\+?\d{8,15}$/.test(
            String(value || '').trim()
        );

// ============================================================
// 📱 تحويل الرقم إلى JID
// ============================================================

const phoneToJid =
    phone => {

        const number =
            String(phone || '')
                .replace(/[^\d]/g, '');

        if (!number) {
            return null;
        }

        return `${number}@s.whatsapp.net`;
    };

// ============================================================
// 👑 أمر السبام
// ============================================================

export default {

    name: "سبام",

    aliases: ["spam"],

    description:
        "إرسال رسالة عدة مرات للمطورين فقط.",

    category: "developer",

    // 👑 الهاندلر هو المسؤول عن التحقق من المطور
    developer: true,

    group: true,

    async run({
        m,
        args,
        text,
        reply,
        sock
    }) {

        const chatId =
            m.key.remoteJid;

        // ========================================================
        // 🔍 قراءة الأمر
        // ========================================================

        let input =
            String(text || '').trim();

        if (!input) {

            return reply(
                `*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*

                 *💥 أمـر الـسـبـام*

*───━━━⊱  💣  ⊰━━━───*

*📌 طـريـقـة الاسـتـخـدام:*

*🔹 .سبام 10 تست*
*└─ يـرسـل "تـسـت" 10 مـرات*

*🔹 .سبام منشن 10 تست*
*└─ يـرسـل "تـسـت" 10 مـرات مـع مـنـشـن مـخـفـي*

*🔹 Reply + .سبام 10*
*└─ يـكـرر الـرسـالـة الـمـردود عـلـيـهـا*

*🔹 Reply + .سبام منشن 10*
*└─ يـكـرر الـرسـالـة مـع مـنـشـن مـخـفـي*

*🔹 .سبام 10 +201xxxxxxxxx تست*
*└─ سـبـام فـي الـخـاص*

*🔹 .سبام 10 +201xxxxxxxxx*
*└─ يـسـتـخـدم الـرسـالـة الـمـردود عـلـيـهـا (ࢪيبـلاي)*

*───━━━⊱  ⚠️  ⊰━━━───*

*🚨 الـحـد الأقـصـى : ⦓ 200 ⦔ رسـالـة*

*🚫 الـمـنـشـن غـيـر مـتـاح فـي الـخـاص*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`
            );
        }

        // ========================================================
        // 🎯 تحديد وضع المنشن
        // ========================================================

        let mentionMode = false;

        if (
            /^منشن(?:\s|$)/i.test(input)
        ) {

            mentionMode = true;

            input =
                input
                    .replace(
                        /^منشن\s*/i,
                        ''
                    )
                    .trim();
        }

        // ========================================================
        // 🔢 استخراج العدد
        // ========================================================

        const countMatch =
            input.match(
                /^(\d+)(?:\s+([\s\S]*))?$/
            );

        if (!countMatch) {

            return reply(
                `*───━━━⊱  ❌  ⊰━━━───*

*❌ صـيـغـة الأمـر غـلـط*

*📌 الـصـح:*

*┋ .سبام 10 تست*
*┋ .سبام منشن 10 تست*
*┋ .سبام 10 +201xxxxxxxxx تست*

*أو اعـمـل Reply واكـتـب:*

*┋ .سبام 10*
*┋ .سبام منشن 10*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`
            );
        }

        const count =
            parseInt(
                countMatch[1],
                10
            );

        let remaining =
            countMatch[2]?.trim() || '';

        // ========================================================
        // 🚨 التحقق من العدد
        // ========================================================

        if (
            !Number.isInteger(count) ||
            count < 1
        ) {

            return reply(
                '*❌ يـجـب أن يـكـون الـعـدد أكـبـر مـن صـفـر*'
            );
        }

        if (
            count > MAX_SPAM
        ) {

            return reply(
                `*🚫 الـحـد الأقـصـى لـلـسـبـام هـو ⦓ ${MAX_SPAM} ⦔ رسـالـة*`
            );
        }

        // ========================================================
        // 💬 بيانات الـ Reply
        // ========================================================

        const contextInfo =
            m.message
                ?.extendedTextMessage
                ?.contextInfo;

        const quotedMessage =
            contextInfo?.quotedMessage;

        // ========================================================
        // 📩 استخراج نص الـ Reply
        // ========================================================

        let quotedText = '';

        if (quotedMessage) {

            quotedText =
                quotedMessage.conversation ||
                quotedMessage
                    .extendedTextMessage
                    ?.text ||
                quotedMessage
                    .imageMessage
                    ?.caption ||
                quotedMessage
                    .videoMessage
                    ?.caption ||
                quotedMessage
                    .documentMessage
                    ?.caption ||
                '';
        }

        // ========================================================
        // 📱 تحديد هل يوجد رقم مستهدف للخاص
        // ========================================================

        let targetJid = null;
        let targetNumber = null;
        let customText = '';

        const parts =
            remaining
                ? remaining.split(/\s+/)
                : [];

        const phoneIndex =
            parts.findIndex(
                part =>
                    isPhoneNumber(part)
            );

        if (
            phoneIndex !== -1
        ) {

            targetNumber =
                parts[phoneIndex];

            targetJid =
                phoneToJid(
                    targetNumber
                );

            customText =
                parts
                    .filter(
                        (_, index) =>
                            index !== phoneIndex
                    )
                    .join(' ')
                    .trim();
        } else {

            customText =
                remaining;
        }

        // ========================================================
        // 🚫 منع المنشن في الخاص
        // ========================================================

        if (
            targetJid &&
            mentionMode
        ) {

            return reply(
                `*───━━━⊱  🚫  ⊰━━━───*

*🚫 الـمـنـشـن غـيـر مـتـاح مـع أرقـام الـخـاص*

*📌 استخدم:*

*┋ .سبام 10 +201xxxxxxxxx تست*

*أو اعـمـل Reply واكـتـب:*

*┋ .سبام 10 +201xxxxxxxxx*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`
            );
        }

        // ========================================================
        // 📝 تحديد محتوى السبام
        // ========================================================

        const spamContent =
            customText ||
            quotedText;

        if (
            !spamContent
        ) {

            return reply(
                `*───━━━⊱  ⚠️  ⊰━━━───*

*⚠️ لازم تكتب رسالة للسبام أو تعمل Reply على رسالة.*

*مثال:*

*┋ .سبام 10 تست*

*أو اعمل Reply واكتب:*

*┋ .سبام 10*

*وللإرسال في الخاص:*

*┋ .سبام 10 +201xxxxxxxxx تست*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`
            );
        }

        // ========================================================
        // 👥 الحصول على أعضاء المجموعة للـ Hidden Mention
        // ========================================================

        let mentions = [];

        if (mentionMode) {

            try {

                const metadata =
                    await sock.groupMetadata(
                        chatId
                    );

                mentions =
                    (metadata?.participants || [])
                        .map(
                            participant =>
                                participant?.id
                        )
                        .filter(Boolean);

                if (
                    mentions.length === 0
                ) {

                    return reply(
                        '*❌ لـم أتـمـكـن مـن الـعـثـور عـلى أعـضـاء الـمـجـمـوعـة*'
                    );
                }

            } catch (error) {

                console.error(
                    'Spam Mention Error:',
                    error
                );

                return reply(
                    '*❌ حـدث خـطـأ أثـنـاء جـلـب أعـضـاء الـمـجـمـوعـة*'
                );
            }
        }

        // ========================================================
        // 📍 تحديد جهة الإرسال
        // ========================================================

        const destination =
            targetJid ||
            chatId;

        // ========================================================
        // 🚀 بدء السبام
        // ========================================================

        const destinationText =
            targetJid
                ? `*📱 الـمـسـتـهـدف :* ⦓ *${targetNumber}* ⦔`
                : '*📍 الـمـكـان :* ⦓ *الـمـجـمـوعـة* ⦔';

        const startMessage =
            `*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*

*💥 بـدء عـمـلـيـة الـسـبـام*

*───━━━⊱  💣  ⊰━━━───*

*📨 الـعـدد :* ⦓ *${count}* ⦔
${destinationText}
*👥 الـمـنـشـن :* ⦓ *${mentionMode ? 'مـخـفـي' : 'مـتـوقـف'}* ⦔
*📝 الـمـحـتـوى :* ⦓ *${spamContent.slice(0, 50)}* ⦔

*⏳ جـاري الإرسـال...*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`;

        await reply(
            startMessage
        );

        // ========================================================
        // 🔥 تنفيذ السبام
        // ========================================================

        let sent = 0;

        for (
            let i = 0;
            i < count;
            i++
        ) {

            try {

                /*
                 * في حالة المنشن:
                 *
                 * النص يظل "تست" فقط.
                 * لا يوجد @ أو أرقام ظاهرة.
                 *
                 * الـmentions يتم إرسالها منفصلة
                 * داخل بيانات الرسالة.
                 */

                const messageContent = {
                    text: spamContent,

                    ...(mentionMode
                        ? {
                            mentions
                        }
                        : {})
                };

                await sock.sendMessage(
                    destination,
                    messageContent
                );

                sent++;

                // ==================================================
                // ⏱️ تأخير بسيط بين الرسائل
                // ==================================================

                if (
                    i < count - 1
                ) {

                    await sleep(
                        SPAM_DELAY
                    );
                }

            } catch (error) {

                console.error(
                    'Spam Send Error:',
                    error
                );

                break;
            }
        }

        // ========================================================
        // ✅ النتيجة
        // ========================================================

        const resultMessage =
            sent === count

                ? `*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*

*✅ تـم إنـهـاء الـسـبـام بـنـجـاح*

*───━━━⊱  💥  ⊰━━━───*

*📨 عـدد الـرسـائـل :* ⦓ *${sent}* ⦔
${targetJid
    ? `*📱 الـمـسـتـهـدف :* ⦓ *${targetNumber}* ⦔`
    : '*📍 الـمـكـان :* ⦓ *الـمـجـمـوعـة* ⦔'}
*👥 الـمـنـشـن :* ⦓ *${mentionMode ? 'مـخـفـي' : 'مـتـوقـف'}* ⦔

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`

                : `*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*

*⚠️ تـم إيـقـاف الـسـبـام*

*───━━━⊱  ⚠️  ⊰━━━───*

*📨 تـم إرسـال :* ⦓ *${sent}* ⦔

*📌 الـمـطـلـوب :* ⦓ *${count}* ⦔

*حـدث خـطـأ أثـنـاء الإرسـال.*

*───━━━⊱  𝐒 𝐎 𝐋 𝐎  ⊰━━━───*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`;

        return reply(
            resultMessage
        );
    }
};