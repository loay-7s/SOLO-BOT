function getQuickReplyId(m) {
    const message =
        m?.message || {};

    /*
     * بعض إصدارات واتساب ترجع
     * Quick Reply كـ Template Reply.
     */
    if (
        message
            .templateButtonReplyMessage
            ?.selectedId
    ) {
        return (
            message
                .templateButtonReplyMessage
                .selectedId
        );
    }

    /*
     * Native Flow.
     */
    const flow =
        message
            .interactiveResponseMessage
            ?.nativeFlowResponseMessage;

    if (flow?.paramsJson) {
        try {
            const data =
                JSON.parse(
                    flow.paramsJson
                );

            return (
                data.id ||
                data.selectedId ||
                data.rowId ||
                data.command ||
                data.button_id ||
                data.buttonId ||
                data.value ||
                null
            );
        } catch {}
    }

    return null;
}

