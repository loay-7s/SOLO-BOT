function normalize(text) {
    return String(text || "")
        .toLowerCase()
        .trim()
        .replace(/ـ/g, "")
        .replace(/[أإآ]/g, "ا")
        .replace(/ى/g, "ي")
        .replace(/[ًٌٍَُِّْ]/g, "")
        .replace(/\s+/g, " ");
}

function shuffle(array) {
    const arr = [...array];

    for (let i = arr.length - 1; i > 0; i--) {
        const j =
            Math.floor(Math.random() * (i + 1));

        [arr[i], arr[j]] =
            [arr[j], arr[i]];
    }

    return arr;
}

