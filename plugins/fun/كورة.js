async function resolveBankJid(
    sock,
    jid
) {
    if (!jid) return null;

    let resolved = jid;

    if (
        resolved.endsWith("@lid") &&
        sock?.signalRepository
            ?.lidMapping
    ) {
        try {
            const pn =
                await sock
                    .signalRepository
                    .lidMapping
                    .getPNForLID(
                        resolved
                    );

            if (pn) {
                resolved = pn;
            }
        } catch {}
    }

    const number =
        resolved
            .split("@")[0]
            .split(":")[0];

    if (!number) {
        return null;
    }

    return (
        `${number}@s.whatsapp.net`
    );
}

async function awardWinner(
    sock,
    sender
) {
    try {
        const userJid =
            await resolveBankJid(
                sock,
                sender
            );

        if (!userJid) {
            throw new Error(
                "تعذر تحديد حساب اللاعب في البنك."
            );
        }

        await fs.ensureFile(
            BANK_PATH
        );

        let bankDB = {};

        try {
            bankDB =
                await fs.readJson(
                    BANK_PATH
                );
        } catch {
            bankDB = {};
        }

        if (
            !bankDB[userJid] ||
            typeof bankDB[userJid] !==
                "object"
        ) {
            bankDB[userJid] = {
                money: 0,
                rank: "مـبـتـدئ 🌱",
                lastDaily: 0,
                inventory: []
            };
        }

        const account =
            bankDB[userJid];

        if (
            !Array.isArray(
                account.inventory
            )
        ) {
            account.inventory = [];
        }

        const currentMoney =
            Number(account.money) ||
            0;

        account.money =
            currentMoney + 20;

        await fs.writeJson(
            BANK_PATH,
            bankDB,
            {
                spaces: 2
            }
        );

        return {
            success: true,
            jid: userJid,
            money: account.money
        };

    } catch (error) {
        console.error(
            "[SOLO KORA BANK]",
            error
        );

        return {
            success: false,
            error:
                error.message
        };
    }
}

/*
 * =========================================================
 * استقبال الإجابات
 * =========================================================
 */

async function handleAnswer(
    sock,
    message
) {
    if (!message?.message)
        return;

    if (message?.key?.fromMe)
        return;

    const chatId =
        getChatId(message);

    if (!chatId)
        return;

    const game =
        games.get(chatId);

    if (!game)
        return;

    const buttonId =
        getQuickReplyId(message);

    const quotedId =
        getQuotedId(message);

    /*
     * لو إجابة زر:
     * لا نحتاج Reply.
     *
     * لو كتابة عادية:
     * نسمح بها فقط لو كانت Reply
     * على سؤال اللعبة.
     */
    const text =
        getMessageText(message);

    if (
        !buttonId &&
        (
            !quotedId ||
            quotedId !==
                game.messageId
        )
    ) {
        return;
    }

    const sender =
        getSender(message);

    if (!sender)
        return;

    let answer = null;

    /*
     * =========================
     * Quick Reply
     * =========================
     */

    if (
        buttonId &&
        /^kora_answer_[0-3]$/
            .test(buttonId)
    ) {
        const index =
            Number(
                buttonId
                    .split("_")
                    .pop()
            );

        if (
            !game.options[index]
        ) {
            return;
        }

        answer =
            normalize(
                game.options[index]
            );
    }

    /*
     * =========================
     * دعم الإجابة النصية القديمة
     * =========================
     */

    else if (text) {
        const value =
            normalize(text);

        if (
            /^[1-4]$/.test(value)
        ) {
            const index =
                Number(value) - 1;

            if (
                !game.options[index]
            ) {
                return;
            }

            answer =
                normalize(
                    game.options[index]
                );

        } else {
            answer = value;
        }
    }

    if (!answer)
        return;

    const correct =
        normalize(
            game.answer
        );

    /*
     * =========================
     * إجابة صحيحة
     * =========================
     */

    if (
        answer === correct
    ) {
        clearTimeout(
            game.timer
        );

        games.delete(
            chatId
        );

        const reward =
            await awardWinner(
                sock,
                sender
            );

        const rewardText =
            reward.success
                ? "+20 عـمـلة"
                : "تعذر إضافة الجائزة للبنك";

        await sock.sendMessage(
            chatId,
            {
                text:
                    createSuccess(
                        sender,
                        game.answer
                    ) +
                    `\n┃ 💰 ${rewardText}`,

                mentions: [
                    sender
                ],

                contextInfo:
                    channelContext(
                        sender
                    )
            },
            {
                quoted:
                    message
            }
        );

        try {
            await sock.sendMessage(
                chatId,
                {
                    react: {
                        text: "🏆",
                        key:
                            message.key
                    }
                }
            );
        } catch {}

        return;
    }

    /*
     * =========================
     * إجابة خاطئة
     * =========================
     */

    const validOption =
        game.options
            .map(normalize)
            .includes(answer);

    if (validOption) {
        await sock.sendMessage(
            chatId,
            {
                text:
                    WRONG_TEXT,

                contextInfo:
                    channelContext(
                        sender
                    )
            },
            {
                quoted:
                    message
            }
        );

        try {
            await sock.sendMessage(
                chatId,
                {
                    react: {
                        text: "❌",
                        key:
                            message.key
                    }
                }
            );
        } catch {}
    }
}

/*
 * =========================================================
 * Listener واحد لكل Socket
 * =========================================================
 */

function registerListener(
    sock
) {
    if (
        !sock ||
        listeners.has(sock)
    ) {
        return;
    }

    const listener =
        async update => {
            try {
                if (
                    !update?.messages
                ) {
                    return;
                }

                for (
                    const message
                    of update.messages
                ) {
                    await handleAnswer(
                        sock,
                        message
                    );
                }
            } catch (error) {
                console.error(
                    "[SOLO KORA LISTENER]",
                    error
                );
            }
        };

    sock.ev.on(
        "messages.upsert",
        listener
    );

    listeners.set(
        sock,
        listener
    );
}

