async function sendNewChoice(sock, chatId) {
    const choice = pickChoice();

    const sent = await sock.sendMessage(chatId, {
        text: buildMessage(choice)
    });

    if (sent?.key?.id) {
        games.set(sent.key.id, {
            chatId,
            a: choice.a,
            b: choice.b,
            createdAt: Date.now()
        });

        setTimeout(() => games.delete(sent.key.id), 10 * 60 * 1000);
    }
}

