// ============================================
// 👂 المستمع
// ============================================
function ensureListener(sock) {
    if (!sock?.ev || listeners.has(sock)) return;
    listeners.add(sock);

    sock.ev.on('messages.upsert', async (update) => {
        try {
            const messages = update?.messages || [];

            for (const msg of messages) {
                if (msg.key.fromMe) continue;
                if (!msg.message) continue;

                const ctx = msg.message?.extendedTextMessage?.contextInfo;
                if (!ctx?.stanzaId) continue;

                const game = games.get(ctx.stanzaId);
                if (!game) continue;
                if (game.chatId !== msg.key.remoteJid) continue;

                const text = (
                    msg.message?.conversation ||
                    msg.message?.extendedTextMessage?.text ||
                    ''
                ).trim();

                if (!text) continue;

                let picked = '';
                if (/^1$/.test(text)) picked = game.a;
                else if (/^2$/.test(text)) picked = game.b;
                else if (/^(١|واحد|الاول|الأول)$/.test(text)) picked = game.a;
                else if (/^(٢|اثنين|الثاني|التاني)$/.test(text)) picked = game.b;

                if (!picked) continue;

                const sender = msg.key.participant || msg.key.remoteJid;
                const senderName = sender.split('@')[0];

                games.delete(ctx.stanzaId);

                await sock.sendMessage(msg.key.remoteJid, {
                    text:
`*⎔┄┄─ ⊱╎⌯ 𝐒 𝐎 𝐋 𝐎 ⌯╎⊰─┄┄⎔*

           *┋ 🍷 اخـتـيـاࢪك جـࢪيء ┋*

*⎔┄┄─── ⊱╎⌯ ✅ ⌯╎⊰ ───┄┄⎔*

*┋ الـعـضـو : ⦓ @${senderName} ⦔*

*⎔┄┄─── ⊱╎⌯ 💭 ⌯╎⊰ ───┄┄⎔*

*┋ اخـتـاࢪ : ${picked}*

*┋ ${picked === game.a ? "🔴 الـخـيـاࢪ الأول" : "🔵 الـخـيـاࢪ الـثـانـي"}*

*⎔┄┄─── ⊱╎⌯ 🏮 ⌯╎⊰ ───┄┄⎔*
> *~『𝑺𝑶𝑳𝑶⊰🏮⊱𝑳𝑬𝑽𝑬𝑳𝑰𝑵𝑮』~*`,
                    mentions: [sender]
                }, { quoted: msg });

                try {
                    await sock.sendMessage(msg.key.remoteJid, {
                        react: { text: "💥", key: msg.key }
                    });
                } catch {}

                setTimeout(async () => {
                    try {
                        await sendNewChoice(sock, msg.key.remoteJid);
                    } catch {}
                }, 3000);
            }
        } catch (err) {
            console.error('❌ [لوخيروك] Listener:', err?.message || err);
        }
    });
}

