// plugins/شاذ.js
// 🏳️‍🌈 SOLO RANDOM TEASER ⚔️

export default {
    name: "شاذ",
    aliases: ["شواذ", "ملك_الشواذ"],
    description: "اختيار عضو عشوائي ليكون ملك الشواذ",
    category: "fun",

    async run({ sock, m, reply, react }) {
        const chatId = m.key.remoteJid;

        try {
            // ═══════════════════════════════════════════════════════
            // ❌ التحقق من المجموعة
            // ═══════════════════════════════════════════════════════
            if (!chatId.endsWith('@g.us')) {
                return reply("*❌ هذا الأمر يعمل فقط في المجموعات!*");
            }

            // ═══════════════════════════════════════════════════════
            // 📥 جلب الأعضاء
            // ═══════════════════════════════════════════════════════
            const groupMetadata = await sock.groupMetadata(chatId);
            const participants = groupMetadata.participants || [];

            // استبعاد البوت
            const botJid = sock.user?.id;
            const members = participants.filter(p => p.id !== botJid);

            if (members.length === 0) {
                return reply("*❌ لا يوجد أعضاء في المجموعة!*");
            }

            // ═══════════════════════════════════════════════════════
            // 🎯 اختيار عضو عشوائي
            // ═══════════════════════════════════════════════════════
            const randomMember = members[Math.floor(Math.random() * members.length)];
            const randomJid = randomMember.id;
            const displayNumber = randomJid.split('@')[0];

            await react("🏳️‍🌈");

            // ═══════════════════════════════════════════════════════
            // 💬 الرسائل — بدون * على @name
            // ═══════════════════════════════════════════════════════
            const messages = [
                `هـتـبـقـى ࢪاجـل امـتـى؟ 🏳️‍🌈`,
                `الـشـواذ كـتـيـࢪ بـس ده اكـبـࢪهـم 🏳️‍🌈`,
                `اهـو الـشـاذ الـدولـي يـاعـم 🏳️‍🌈`,
                `فـخـر الـشـواذ يـا عـم 🏳️‍🌈`,
                `تـاج الـشـواذ ع راسـك 🏳️‍🌈`,
                `مـلـك الـشـواذ بـنـفـسـه 👑🏳️‍🌈`,
                `اكـبـࢪ شـاذ فـي الـتـاريـخ 🏳️‍🌈`,
                `يـا اسـطـورة الـشـواذ 🏳️‍🌈`,
                `مـحـدش شـاذ قـدك يـا كـبـيـࢪهـم 🏳️‍🌈`,
                `اهـو الـلـي كـل الـشـواذ بـيـتـعـلـمـوا مـنـه 🏳️‍🌈`,
                `ده لـو الـشـذوذ لـيـه مـلـك كـان ده بـنـفـسـه 🏳️‍🌈`,
                `شـاذ و مـفـتـخـࢪ بـنـفـسـه 🏳️‍🌈`,
                `يـا جـوكـر الـشـواذ 🃏🏳️‍🌈`,
                `قـدوة الـشـواذ بـنـفـسـه 🏳️‍🌈`,
                `مـدࢪسـة الـشـواذ الـدولـيـة 😎🏳️‍🌈`,
                `يـا شـيـخ الـشـواذ مـحـتـاجـيـن نـظـام جـديـد 🏳️‍🌈`,
                `شـاذ بـس بـنـحـبـه ❤️🏳️‍🌈`,
                `الـشـاذ الـهـلـفـوت الـلـي لـو حـد شـافـه يـمـوت 🏳️‍🌈`,
                `هـتـفـضـل شـاذ طـول عـمـࢪك؟ 🏳️‍🌈`,
                `الـشـاذ الـهـلـفـوت 🏳️‍🌈`,
                `يـا نـجـم الـشـواذ الأول 🌟🏳️‍🌈`,
                `أسـطـورة الـشـواذ الـدولـي 📜🏳️‍🌈`,
                `يـا بـطـل الـشـواذ الـحـقـيـقـي 🏳️‍🌈`,
                `شـاذ و مـش بـيـخـبـي 🏳️‍🌈`,
                `اهـو الـشـاذ الأسـاسـي فـي الـجـروب 🏳️‍🌈`,
                `يـا كـبـيـر الـشـواذ 🏳️‍🌈`,
                `مـلـك الـشـواذ الـمـطـلـق 👑🏳️‍🌈`,
                `شـاذ مـن الـدرجـة الأولـى 🏳️‍🌈`,
                `يـا وحـش الـشـواذ 🦁🏳️‍🌈`,
                `الـشـاذ الـمـثـالـي فـي الـجـروب 🏳️‍🌈`,
                `يـا قـائـد الـشـواذ 🚀🏳️‍🌈`,
                `اهـو الـشـاذ الـلـي بـيـعـمـل جـو 🏳️‍🌈`,
                `يـا نـجـم الـشـواذ الـسـاطـع ⭐🏳️‍🌈`
            ];

            // ═══════════════════════════════════════════════════════
            // 🎲 اختيار رسالة عشوائية
            // ═══════════════════════════════════════════════════════
            const randomMessage = messages[Math.floor(Math.random() * messages.length)];

            // ═══════════════════════════════════════════════════════
            // 📤 إرسال — الشكل المطلوب:
            //   *☜@name  نص الرسالة*
            // ═══════════════════════════════════════════════════════
            await sock.sendMessage(chatId, {
                text: `*☜@${displayNumber}  ${randomMessage}*`,
                mentions: [randomJid]
            }, { quoted: m });

        } catch (error) {
            console.error("❌ شاذ Error:", error);
            await reply(`❌ *حدث خطأ:*\n${error.message}`);
        }
    }
};