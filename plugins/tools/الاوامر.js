async function sendButtonNormal(sock, jid, data, quoted) {
    let mediaBuffer;

    if (Buffer.isBuffer(data.media)) {
        mediaBuffer = data.media;
    } else if (
        typeof data.media === "object" &&
        data.media?.buffer
    ) {
        mediaBuffer = data.media.buffer;
    } else if (
        typeof data.media === "object" &&
        data.media?.url
    ) {
        const response = await fetch(data.media.url);

        if (!response.ok) {
            throw new Error(
                `Failed to download media: ${response.status}`
            );
        }

        mediaBuffer = Buffer.from(
            await response.arrayBuffer()
        );
    } else if (typeof data.media === "string") {
        const response = await fetch(data.media);

        if (!response.ok) {
            throw new Error(
                `Failed to download media: ${response.status}`
            );
        }

        mediaBuffer = Buffer.from(
            await response.arrayBuffer()
        );
    } else {
        throw new Error("Invalid media format");
    }

    const uploaded = await prepareWAMessageMedia(
        data.mediaType === "video"
            ? { video: mediaBuffer }
            : { image: mediaBuffer },
        {
            upload: sock.waUploadToServer
        }
    );

    const buttons = (data.buttons || []).map((button) => ({
        name: button.name,
        buttonParamsJson: JSON.stringify(
            button.params || {}
        )
    }));

    const contextInfo = {};

    if (data.mentions?.length) {
        contextInfo.mentionedJid = data.mentions;
    }

    const interactiveMessage = {
        header: {
            [data.mediaType === "video"
                ? "videoMessage"
                : "imageMessage"]:
                data.mediaType === "video"
                    ? uploaded.videoMessage
                    : uploaded.imageMessage,
            hasMediaAttachment: true
        },

        body: {
            text: data.caption || ""
        },

        footer: {
            text: data.footer || ""
        },

        contextInfo,

        nativeFlowMessage: {
            buttons
        }
    };

    const waMessage =
        generateWAMessageFromContent(
            jid,
            {
                interactiveMessage
            },
            {
                userJid: sock.user?.id,
                quoted
            }
        );

    await sock.relayMessage(
        jid,
        waMessage.message,
        {
            messageId: waMessage.key.id,

            additionalNodes: [
                {
                    tag: "biz",
                    attrs: {},

                    content: [
                        {
                            tag: "interactive",

                            attrs: {
                                type: "native_flow",
                                v: "1"
                            },

                            content: [
                                {
                                    tag: "native_flow",

                                    attrs: {
                                        v: "9",
                                        name: "mixed"
                                    }
                                }
                            ]
                        }
                    ]
                }
            ]
        }
    );

    return waMessage;
}

