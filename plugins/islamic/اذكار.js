async function sendZikr(sock, chatId, message, sectionName) {
    const section = getSectionByName(sectionName);
    if (!section) return false;

    const total = section.azkar.length;

    let text = `${SOLO_HEADER}\n\n`;
    text += `*${section.emoji} ${zakhrifName(section.name)} ${section.emoji}*\n\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n`;
    text += `*📿 عـدد الأذكـار : ${total}*\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;

    section.azkar.forEach((zikr, i) => {
        text += `*◈┄┄『 ${i + 1} 』┄┄◈*\n`;
        text += `*⦓ ${zikr} ⦔*\n\n`;
    });

    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;
    text += `*📿 اذكـر الله دائمـاً*\n`;
    text += `*💡 الـذكـر يـطـمـئـن الـقـلـوب*\n\n`;
    text += `${SOLO_FOOTER}`;

    await sock.sendMessage(chatId, { text }, { quoted: message });
    return true;
}

