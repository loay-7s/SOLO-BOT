function getSectionList() {
    const list = [];
    let index = 1;
    for (const [sectionName, section] of Object.entries(AZKAR_SECTIONS)) {
        list.push({
            index,
            name: sectionName,
            emoji: section.emoji,
            count: section.azkar.length
        });
        index++;
    }
    return list;
}

function getSectionByName(name) {
    if (AZKAR_SECTIONS[name]) return { name, ...AZKAR_SECTIONS[name] };
    for (const [sectionName, section] of Object.entries(AZKAR_SECTIONS)) {
        if (sectionName.includes(name) || name.includes(sectionName)) {
            return { name: sectionName, ...section };
        }
    }
    return null;
}

function getSectionByIndex(index) {
    const list = Object.keys(AZKAR_SECTIONS);
    if (index < 1 || index > list.length) return null;
    const name = list[index - 1];
    return { name, ...AZKAR_SECTIONS[name] };
}

