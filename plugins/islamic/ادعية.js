async function sendDua(sock, chatId, message, sectionName) {
    const section = getSectionByName(sectionName);
    if (!section) return false;

    const total = section.duas.length;

    let text = `${SOLO_HEADER}\n\n`;
    text += `*${section.emoji} ${zakhrifName(section.name)} ${section.emoji}*\n\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n`;
    text += `*🤲 عـدد الأدعـيـة : ${total}*\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;

    section.duas.forEach((dua, i) => {
        text += `*◈┄┄『 ${i + 1} 』┄┄◈*\n`;
        text += `*⦓ ${dua} ⦔*\n\n`;
    });

    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;
    text += `*🤲 اد؏ُ الله بـقـلـبً خـاشـع*\n`;
    text += `*💡 إن الـدعـاء عـبـادة*\n\n`;
    text += `${SOLO_FOOTER}`;

    await sock.sendMessage(chatId, { text }, { quoted: message });
    return true;
}

