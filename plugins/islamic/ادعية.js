export default {
    name: "ادعية",
    aliases: ["أدعية","ادعيه" ,"دعاء", "دعاوي"],
    description: "نظام أدعية شامل بأقسام متعددة",
    category: "إسلاميات",

    async run({ sock, message, args, reply, react }) {
        const chatId = message.key.remoteJid;

        try {
            await react("🤲");

            if (!args || args.length === 0) {
                await sendSectionsMenu(sock, chatId, message);
                return;
            }

            const input = String(args[0]).trim();

            if (/^\d+$/.test(input)) {
                const index = parseInt(input, 10);
                const section = getSectionByIndex(index);

                if (!section) {
                    await react("❌");
                    return reply(`*❌ الـࢪقـم غـيـࢪ صـالـح*\n\n📌 مـن 1 لـ ${Object.keys(DUA_SECTIONS).length}`);
                }

                await sendDua(sock, chatId, message, section.name);
                await react("✅");
                return;
            }

            const fullInput = args.join(' ');
            const section = getSectionByName(fullInput);

            if (!section) {
                await react("❌");
                return reply(`*❌ الـقـسـم غـيـࢪ مـوجـود*\n\n📌 اكـتـب \`.ادعية\` لـعـرض الأقـسـام`);
            }

            await sendDua(sock, chatId, message, section.name);
            await react("✅");

        } catch (error) {
            console.error("❌ Dua Error:", error);
            await react("❌");
            await reply(`*❌ فـشـل الأمـر*\n📌 ${error.message}`);
        }
    }
};