function getSectionList() {
    const list = [];
    let index = 1;
    for (const [sectionName, section] of Object.entries(HADITH_SECTIONS)) {
        list.push({
            index,
            name: sectionName,
            emoji: section.emoji,
            count: section.ahadith.length
        });
        index++;
    }
    return list;
}

function getSectionByName(name) {
    if (HADITH_SECTIONS[name]) return { name, ...HADITH_SECTIONS[name] };
    for (const [sectionName, section] of Object.entries(HADITH_SECTIONS)) {
        if (sectionName.includes(name) || name.includes(sectionName)) {
            return { name: sectionName, ...section };
        }
    }
    return null;
}

function getSectionByIndex(index) {
    const list = Object.keys(HADITH_SECTIONS);
    if (index < 1 || index > list.length) return null;
    const name = list[index - 1];
    return { name, ...HADITH_SECTIONS[name] };
}

