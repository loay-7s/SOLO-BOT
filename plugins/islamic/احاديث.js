async function sendAhadith(sock, chatId, message, sectionName) {
    const section = getSectionByName(sectionName);
    if (!section) return false;

    const total = section.ahadith.length;

    let text = `${SOLO_HEADER}\n\n`;
    text += `*${section.emoji} ${zakhrifName(section.name)} ${section.emoji}*\n\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n`;
    text += `*📜 عـدد الأحـاديـث : ${total}*\n`;
    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;

    section.ahadith.forEach((hadith, i) => {
        text += `*◈┄┄『 ${i + 1} 』┄┄◈*\n`;
        text += `*⦓ ${hadith} ⦔*\n\n`;
    });

    text += `*⎔┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄┄⎔*\n\n`;
    text += `*📜 قـال ࢪسـول الله ﷺ*\n`;
    text += `*💡 الـسـنـة الـنـبـويـة*\n\n`;
    text += `${SOLO_FOOTER}`;

    await sock.sendMessage(chatId, { text }, { quoted: message });
    return true;
}

